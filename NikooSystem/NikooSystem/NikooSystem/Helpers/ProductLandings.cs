    /// <summary>
    /// A landing page for one group of Nikoo's products (/online-shop, /online-booking, ...): the page people land on from
    /// Google for «فروشگاه اینترنتی آماده» and the like, so it explains the product fully and links to demos and signup.
    /// In the texts, {SiteName}, {TrialDays} and {TemplateCount} are filled in when the page is shown.
    /// </summary>
    public sealed class ProductLanding
    {
        public string Slug { get; set; }
        /// <summary>Short name for menus and links.</summary>
        public string Name { get; set; }
        /// <summary>One line under the name in menus and cards.</summary>
        public string Summary { get; set; }
        public string Icon { get; set; }
        public string Image { get; set; }

        /// <summary>The <see cref="SiteKinds"/> the page sells; null for the templates page, which shows every kind.</summary>
        public string Kind { get; set; }
        /// <summary>The store types offered on the page, the first being the one the main buttons sign up for.</summary>
        public string[] Types { get; set; }
        /// <summary>Only templates drawn on this layout (corporate or news sites share one kind); null = all of the kind.</summary>
        public string TemplateLayout { get; set; }
        /// <summary>Words that tie a blog article to the page, matched against its title, tags and summary.</summary>
        public string[] Keywords { get; set; }

        public string Heading { get; set; }
        public string SeoTitle { get; set; }
        public string Description { get; set; }
        public string Lead { get; set; }

        public string IntroTitle { get; set; }
        public string[] Intro { get; set; }
        public string[] Audience { get; set; }
        public PlatformModule[] Highlights { get; set; }
        public Tuple<string, string>[] Steps { get; set; }
        public SiteFaq[] Faqs { get; set; }

        public string MainType => Types?.FirstOrDefault();

        public SiteKindInfo KindInfo => Kind == null ? null : SiteKinds.Get(Kind);
    }

