        public static ProductLanding Get(string slug) =>
            All.FirstOrDefault(p => string.Equals(p.Slug, (slug ?? "").Trim(), StringComparison.OrdinalIgnoreCase));

        /// <summary>The landing page that sells <paramref name="storeType"/>, or null.</summary>
        public static ProductLanding ForType(string storeType) =>
            All.FirstOrDefault(p => p.Types != null && p.Types.Contains(storeType));

        /// <summary>The route constraint that keeps the one-segment landing addresses from catching other pages.</summary>
        public static string SlugPattern => string.Join("|", All.Select(p => p.Slug));

        /// <summary>Fills the {SiteName}, {TrialDays} and {TemplateCount} placeholders of a landing text.</summary>
        public static string Fill(string text, string siteName)
        {
            if (string.IsNullOrEmpty(text)) return text;
            return text
                .Replace("{SiteName}", siteName)
                .Replace("{TrialDays}", Services.TenantProvisioningService.TrialDays.ToString().ToFaDigits())
                .Replace("{TemplateCount}", StoreTemplates.All.Count.ToString().ToFaDigits());
        }

        /// <summary>The templates the page shows: those of its kind, or only the ones drawn on its layout.</summary>
        public static List<StoreTemplateInfo> Templates(this ProductLanding page) =>
            page.Kind == null
                ? new List<StoreTemplateInfo>()
                : StoreTemplates.ForKind(page.Kind).Where(t => page.TemplateLayout == null || t.Layout == page.TemplateLayout).ToList();

        private static PlatformModule Highlight(string icon, string name, string summary) =>
            new PlatformModule { Icon = icon, Name = name, Summary = summary };

        private static Tuple<string, string> Step(string title, string text) => Tuple.Create(title, text);

        private static SiteFaq Faq(string question, string answer) => new SiteFaq { Question = question, Answer = answer };
    }

    /// <summary>The «قالب‌های آماده» section: templates shown live on the demo of <see cref="Type"/>.</summary>
    public sealed class TemplateShowcase
    {
        public StoreTypeInfo Type { get; set; }
        public List<StoreTemplateInfo> Templates { get; set; }
        /// <summary>Null = «N قالب آماده برای این محصول».</summary>
        public string Heading { get; set; }
        public string SectionId { get; set; } = "templates";

        /// <summary>The templates of the store type's kind, its default first, optionally only those drawn on <paramref name="layout"/>.</summary>
        public static TemplateShowcase For(string storeType, string layout = null, string heading = null, string sectionId = "templates")
        {
            var type = StoreTypes.Get(storeType);
            return new TemplateShowcase
            {
                Type = type,
                Templates = StoreTemplates.ForKind(type.Kind)
                    .Where(t => layout == null || t.Layout == layout)
                    .OrderByDescending(t => t.Id == type.DefaultTemplate)
                    .ToList(),
                Heading = heading,
                SectionId = sectionId
            };
        }
    }
