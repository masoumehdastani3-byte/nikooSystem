<#
.SYNOPSIS
    Writes NikooSystem\App_Data\Seed\tutorials.sql from the tutorial tables of the nikoo database.

.DESCRIPTION
    The tours and the record of which video matches which page version live in the database
    (Tutorials, TutorialViews, TutorialSteps, TutorialVideos). This script turns them into a SQL script that ships
    with the site; on start, the site applies it whenever its content changed, so other servers get the same
    tutorials as the database it was exported from. update-tutorials.ps1 runs it after recording.

.EXAMPLE
    .\export-tutorials.ps1
#>
param([string]$ConnectionString)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'db.ps1')
$site = (Resolve-Path (Join-Path $PSScriptRoot '..\..\NikooSystem')).Path
if (-not $ConnectionString) { $ConnectionString = Get-NikooConnectionString $site }

function ConvertTo-SqlLiteral($value) {
    if ($null -eq $value -or $value -is [DBNull]) { return 'NULL' }
    if ($value -is [bool]) { return $(if ($value) { '1' } else { '0' }) }
    if ($value -is [int] -or $value -is [long]) { return [string]$value }
    if ($value -is [datetime]) { return "'" + $value.ToString('yyyy-MM-ddTHH:mm:ss.fffffff', [Globalization.CultureInfo]::InvariantCulture) + "'" }
    "N'" + ([string]$value).Replace("'", "''") + "'"
}

$tables = [ordered]@{
    Tutorials      = '[Page]'
    TutorialViews  = '[Page], [Position]'
    TutorialSteps  = '[Page], [Position]'
    TutorialVideos = '[Page]'
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('-- Generated by tools\tutorials\export-tutorials.ps1 from the nikoo database. Do not edit by hand:')
$lines.Add('-- change the tutorial tables and export again. Applied by the site on start when this file changes.')
$lines.Add('DELETE FROM [dbo].[TutorialVideos];')
$lines.Add('DELETE FROM [dbo].[Tutorials];')
foreach ($table in $tables.Keys) {
    $rows = Invoke-NikooQuery $ConnectionString "SELECT * FROM [dbo].[$table] ORDER BY $($tables[$table])"
    $columns = @($rows.Columns | ForEach-Object { $_.ColumnName })
    $columnList = ($columns | ForEach-Object { "[$_]" }) -join ', '
    foreach ($row in $rows.Rows) {
        $values = ($columns | ForEach-Object { ConvertTo-SqlLiteral $row[$_] }) -join ', '
        $lines.Add("INSERT INTO [dbo].[$table] ($columnList) VALUES ($values);")
    }
}

$seedDir = Join-Path $site 'App_Data\Seed'
New-Item -ItemType Directory -Force -Path $seedDir | Out-Null
$seedFile = Join-Path $seedDir 'tutorials.sql'
[IO.File]::WriteAllText($seedFile, ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $seedFile ($($lines.Count - 4) rows)."
